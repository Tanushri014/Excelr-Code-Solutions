package day7assignment;

public class Student {
	private String name;
	private int age;
	public Student() {
		this.name="default";
		this.age=0;
	}
	public Student(String name, int age) {
		super();
		this.name = name;
		this.age = age;
	}
	public Student(String name) {
		super();
		this.name = name;
		
	}
	

}
